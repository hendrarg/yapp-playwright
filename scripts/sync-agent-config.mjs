/**
 * Project `.agents/` into each AI tool's own discovery path.
 *
 * `AGENTS.md` + `.agents/` are the single source of truth for every agent working
 * on this repo. Rules travel fine as-is — `AGENTS.md` is a cross-tool convention,
 * and OpenCode can glob `.agents/rules/*` straight from `opencode.json`. Skills and
 * slash commands cannot: each tool defines its own format and only scans its own
 * directory, so they get copied here instead.
 *
 * Everything this script writes is git-ignored and disposable. Edit `.agents/`.
 *
 * Targets:
 *   .claude/skills/<name>/SKILL.md   <- .agents/skills/<name>/SKILL.md
 *   .claude/commands/<name>.md       <- .agents/commands/<name>.md
 *   .opencode/commands/<name>.md     <- .agents/commands/<name>.md
 *   .cursor/rules/<name>.mdc         <- .agents/rules/<name>.md
 *
 * Codex needs no adapter: it reads AGENTS.md from the repo root on its own, and its
 * custom prompts are deprecated and live in ~/.codex, outside any repository.
 *
 * Usage:
 *   node scripts/sync-agent-config.mjs            # write adapters
 *   node scripts/sync-agent-config.mjs --check    # exit 1 if any adapter is stale
 *   node scripts/sync-agent-config.mjs --quiet    # only report the summary (postinstall)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const quiet = args.includes("--quiet");

const BANNER_PREFIX = "<!-- GENERATED by scripts/sync-agent-config.mjs from";

/**
 * Rules Cursor should always load, mirroring the "Required Agent Runtime" list in
 * AGENTS.md. The rest stay agent-requested so Cursor's always-on context stays small.
 */
const CURSOR_ALWAYS_APPLY = new Set(["code-style", "testing"]);

/** One-line summary per rule, used as the Cursor `description` frontmatter field. */
const RULE_DESCRIPTIONS = {
  "code-style": "Imports, page objects, smartLocator selector priority, and the Mandatory Reuse Gate",
  testing: "Fixture selection, nav routes, minimum test depth, tagging, API seeding, and verification",
  "git-hygiene": "Working-tree safety, secret handling, and non-destructive git usage",
  ci: "GitHub Actions scope, required CI environment, secrets, and CI validation commands",
  "mcp-playwright": "MCP Playwright server registration, token injection, and OTP token refresh",
};

let written = 0;
let stale = [];

function banner(sourceRel) {
  return `${BANNER_PREFIX} ${sourceRel.replace(/\\/g, "/")}. Do not edit — edit the source. -->`;
}

/** Write `content` to `destAbs`, or record it as stale under --check. */
function emit(destAbs, content) {
  const destRel = path.relative(root, destAbs).replace(/\\/g, "/");
  const current = fs.existsSync(destAbs) ? fs.readFileSync(destAbs, "utf8") : null;
  if (current === content) return;
  if (check) {
    stale.push(destRel);
    return;
  }
  fs.mkdirSync(path.dirname(destAbs), { recursive: true });
  fs.writeFileSync(destAbs, content);
  written += 1;
  if (!quiet) console.log(`  wrote ${destRel}`);
}

function listFiles(dir, ext) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(ext))
    .map((e) => e.name)
    .sort();
}

/** Split leading YAML frontmatter off a markdown file. */
function splitFrontmatter(text) {
  if (!text.startsWith("---")) return { frontmatter: null, body: text };
  const end = text.indexOf("\n---", 3);
  if (end === -1) return { frontmatter: null, body: text };
  const close = text.indexOf("\n", end + 1);
  return {
    frontmatter: text.slice(0, close === -1 ? text.length : close),
    body: close === -1 ? "" : text.slice(close + 1),
  };
}

/**
 * Copy a markdown file, inserting the generated-file banner after any frontmatter
 * so tools that parse frontmatter (skills, commands) still see it first.
 */
function copyMarkdown(srcAbs, destAbs) {
  const srcRel = path.relative(root, srcAbs);
  const raw = fs.readFileSync(srcAbs, "utf8");
  const { frontmatter, body } = splitFrontmatter(raw);
  const content = frontmatter
    ? `${frontmatter}\n${banner(srcRel)}\n\n${body.replace(/^\n+/, "")}`
    : `${banner(srcRel)}\n\n${raw.replace(/^\n+/, "")}`;
  emit(destAbs, content);
}

// ── Claude Code: skills ───────────────────────────────────────────
const skillsDir = path.join(root, ".agents", "skills");
if (fs.existsSync(skillsDir)) {
  for (const entry of fs.readdirSync(skillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const src = path.join(skillsDir, entry.name, "SKILL.md");
    // A directory without SKILL.md is a leftover, not a skill — skip it silently.
    if (!fs.existsSync(src)) continue;
    copyMarkdown(src, path.join(root, ".claude", "skills", entry.name, "SKILL.md"));
  }
}

// ── Claude Code + OpenCode: slash commands ────────────────────────
const commandsDir = path.join(root, ".agents", "commands");
for (const name of listFiles(commandsDir, ".md")) {
  const src = path.join(commandsDir, name);
  copyMarkdown(src, path.join(root, ".claude", "commands", name));
  copyMarkdown(src, path.join(root, ".opencode", "commands", name));
}

// ── Cursor: rules as .mdc with Cursor's frontmatter ───────────────
const rulesDir = path.join(root, ".agents", "rules");
for (const name of listFiles(rulesDir, ".md")) {
  const slug = name.replace(/\.md$/, "");
  const srcAbs = path.join(rulesDir, name);
  const body = fs.readFileSync(srcAbs, "utf8");
  const always = CURSOR_ALWAYS_APPLY.has(slug);
  const description = RULE_DESCRIPTIONS[slug] ?? `Project rule: ${slug}`;
  const frontmatter = [
    "---",
    `description: ${description}`,
    // Rules govern the whole automation codebase, not one file type.
    "globs:",
    `alwaysApply: ${always}`,
    "---",
  ].join("\n");
  const content = `${frontmatter}\n${banner(path.relative(root, srcAbs))}\n\n${body.replace(/^\n+/, "")}`;
  emit(path.join(root, ".cursor", "rules", `${slug}.mdc`), content);
}

// ── Report ────────────────────────────────────────────────────────
if (check) {
  if (stale.length) {
    console.error(`[agents:sync] ${stale.length} adapter(s) out of date:`);
    for (const s of stale) console.error(`  ${s}`);
    console.error("Run `npm run agents:sync` to regenerate.");
    process.exit(1);
  }
  console.log("[agents:sync] all adapters up to date");
} else if (!quiet || written) {
  console.log(`[agents:sync] ${written} adapter file(s) written from .agents/`);
}
