/**
 * Delete local test/MCP artifacts so they stop accumulating.
 *
 * The MCP Playwright server writes a console log and an accessibility snapshot
 * for nearly every interaction into `.playwright-mcp/`, and stray `page-*.yml`
 * dumps sometimes land in the repo root. None of it is committed, but left
 * alone it grows without bound (22 MB / 657 files before the first cleanup).
 *
 * Usage:
 *   node scripts/clean-artifacts.mjs                 # delete artifacts older than 7 days
 *   node scripts/clean-artifacts.mjs --days=0        # delete all artifacts
 *   node scripts/clean-artifacts.mjs --dry-run       # list what would go
 *   node scripts/clean-artifacts.mjs --reports       # also clear test-results/ + playwright-report/
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const withReports = args.includes("--reports");
const daysArg = args.find((a) => a.startsWith("--days="));
const days = daysArg ? Number(daysArg.split("=")[1]) : 7;

if (!Number.isFinite(days) || days < 0) {
  console.error(`Invalid --days value: ${daysArg}`);
  process.exit(1);
}

/** Regenerated by scripts/mcp-auth-storage.mjs on MCP start, but cheap to keep. */
const KEEP = new Set(["auth-storage.json"]);
const cutoff = Date.now() - days * 24 * 60 * 60 * 1000;

let removedFiles = 0;
let removedBytes = 0;

function rm(target, size) {
  if (dryRun) {
    console.log(`would remove ${path.relative(root, target)}`);
  } else {
    fs.rmSync(target, { recursive: true, force: true });
  }
  removedFiles += 1;
  removedBytes += size;
}

/** Recursively remove entries older than the cutoff; prune dirs left empty. */
function sweepDir(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (KEEP.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      sweepDir(full);
      // Prune the directory only once it is genuinely empty.
      if (fs.existsSync(full) && fs.readdirSync(full).length === 0 && !dryRun) {
        fs.rmdirSync(full);
      }
      continue;
    }
    const stat = fs.statSync(full);
    if (stat.mtimeMs < cutoff) rm(full, stat.size);
  }
}

// 1. MCP console logs and page snapshots.
sweepDir(path.join(root, ".playwright-mcp"));

// 2. Stray snapshot dumps written to the repo root.
for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
  if (!entry.isFile() || !/\.ya?ml$/i.test(entry.name)) continue;
  const full = path.join(root, entry.name);
  const stat = fs.statSync(full);
  if (stat.mtimeMs < cutoff) rm(full, stat.size);
}

// 3. Machine-generated MCP dumps kept under local automation plans.
const plans = path.join(root, "docs", "automation-plans");
if (fs.existsSync(plans)) {
  for (const entry of fs.readdirSync(plans, { withFileTypes: true })) {
    if (entry.isDirectory() && entry.name.endsWith("-snapshots")) {
      sweepDir(path.join(plans, entry.name));
    }
  }
}

// 4. Playwright reports and traces, only when asked.
if (withReports) {
  for (const dir of ["test-results", "playwright-report", "blob-report"]) {
    const full = path.join(root, dir);
    if (fs.existsSync(full)) rm(full, 0);
  }
}

const mb = (removedBytes / 1024 / 1024).toFixed(1);
const verb = dryRun ? "would remove" : "removed";
console.log(
  `[clean-artifacts] ${verb} ${removedFiles} item(s), ${mb} MB (older than ${days} day(s))`,
);
